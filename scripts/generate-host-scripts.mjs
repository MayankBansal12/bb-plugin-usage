import { readFile, writeFile } from "node:fs/promises";
import ts from "typescript";

// Compile the host functions before BB bundles the server. Serializing a bundled
// function with toString() also copies references to bundler helpers whose scope
// does not exist on the enrolled machine (e.g. esbuild's keepNames helper).
const functions = [
  ["lib/host-json-collector.ts", "hostJsonCollector"],
  ["lib/devin-sqlite-collector.ts", "devinSqliteCollector"],
  ["lib/grok-limits.ts", "normalizeGrokBilling"],
];
const root = new URL("../", import.meta.url);
const output = new URL("lib/host-scripts.generated.ts", root);
let generated = "// Generated by npm run generate:collectors. Edit the original TypeScript functions.\n"
  + "// Checked in so BB's direct Git/path builds do not need a prebuild hook.\n\n";
for (const [file, name] of functions) {
  const source = ts.createSourceFile(file, await readFile(new URL(file, root), "utf8"), ts.ScriptTarget.ES2022, true);
  const fn = source.statements.find((node) => ts.isFunctionDeclaration(node) && node.name?.text === name);
  if (!fn) throw new Error(`Missing host function ${name} in ${file}`);
  const { outputText, diagnostics } = ts.transpileModule(fn.getText(source).replace(/^export\s+/, ""), {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.None, removeComments: true },
    reportDiagnostics: true,
  });
  if (diagnostics?.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
    getCanonicalFileName: (file) => file, getCurrentDirectory: () => "", getNewLine: () => "\n",
  }));
  generated += `export const ${name}Source = ${JSON.stringify(outputText.trim())};\n\n`;
}
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8").catch(() => "") !== generated) {
    throw new Error("Host scripts are stale. Run npm run generate:collectors and commit the generated file.");
  }
} else {
  await writeFile(output, generated);
}
